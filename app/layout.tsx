import { ThemeProvider } from '@/providers/ThemeProvider'
import type { Metadata } from 'next'
import { Geist, Geist_Mono } from 'next/font/google'
import './globals.css'

const geistSans = Geist({
  variable: '--font-geist-sans',
  subsets: ['latin'],
})

const geistMono = Geist_Mono({
  variable: '--font-geist-mono',
  subsets: ['latin'],
})

export const metadata: Metadata = {
  title: 'Subway configurator',
  description: 'Generated by create next app',
}

// Выполняется до гидрации и до первой отрисовки — тема применяется без мигания.
// Дефолт — dark (как THEME_VALUE.DARK в провайдере).
const themeScript = `
(function () {
  try {
    var stored = localStorage.getItem('theme');
    var theme = stored ? JSON.parse(stored) : 'dark';
    if (theme === 'dark') document.documentElement.classList.add('dark');
  } catch (e) {
    document.documentElement.classList.add('dark');
  }
})();
`

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    // suppressHydrationWarning: скрипт меняет class у <html> до гидрации
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable}`}
      suppressHydrationWarning
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: themeScript }} />
      </head>
      <body>
        <ThemeProvider>{children}</ThemeProvider>
      </body>
    </html>
  )
}
